import { app, BrowserWindow, ipcMain, net, shell } from 'electron'
import { createWriteStream } from 'fs'
import { join } from 'path'
import { tmpdir } from 'os'
import { rm } from 'fs/promises'
import electronUpdater, { type AppUpdater, type UpdateInfo as UpdaterFeedInfo } from 'electron-updater'
import type { UpdaterState } from '../shared/types'
import { loadSettings } from './saves/saveSettings'

/**
 * "Обновления по воздуху": the launcher checks GitHub Releases for a newer
 * version, downloads it in the background and installs it from inside the app.
 *
 * Installed (NSIS) builds are updated with electron-updater, which reads the
 * `app-update.yml` / `latest.yml` feed generated by electron-builder and can
 * run the installer with `quitAndInstall()`.
 *
 * Portable builds have no persistent install for an NSIS patcher to target, so
 * electron-updater refuses to run. For those we fall back to the GitHub API:
 * download the `*-setup.exe` asset with progress and launch it.
 */

const REPO = 'TheDanDARAK/vavilon'
const CHECK_INTERVAL_MS = 6 * 60 * 60 * 1000

/** Portable target exports this directory; installed builds do not. */
function isPortable(): boolean {
  return Boolean(process.env.PORTABLE_EXECUTABLE_DIR)
}

/**
 * electron-updater is CommonJS; when the main bundle is ESM the named import
 * can be undefined. Destructuring the default export works in both formats.
 */
function getAutoUpdater(): AppUpdater {
  return (electronUpdater as { autoUpdater: AppUpdater }).autoUpdater
}

let state: UpdaterState = {
  phase: 'idle',
  current: app.getVersion(),
  portable: isPortable()
}

/** Path of a manually downloaded installer (portable fallback) */
let manualInstaller: string | null = null
let timer: NodeJS.Timeout | null = null
let initialized = false

function emit(): void {
  for (const win of BrowserWindow.getAllWindows()) {
    win.webContents.send('updater:state', state)
  }
}

function patch(next: Partial<UpdaterState>): void {
  state = { ...state, ...next, current: app.getVersion(), portable: isPortable() }
  emit()
}

export function getUpdaterState(): UpdaterState {
  return state
}

interface GithubRelease {
  tag_name?: string
  html_url?: string
  body?: string
  assets?: Array<{ name: string; browser_download_url: string; size?: number }>
}

async function fetchLatestRelease(): Promise<GithubRelease> {
  const res = await net.fetch(`https://api.github.com/repos/${REPO}/releases/latest`, {
    headers: {
      Accept: 'application/vnd.github+json',
      'User-Agent': `vavilon/${app.getVersion()}`,
      'X-GitHub-Api-Version': '2022-11-28'
    },
    signal: AbortSignal.timeout(20000)
  })
  if (!res.ok) throw new Error(`GitHub вернул ${res.status}`)
  return (await res.json()) as GithubRelease
}

/** The NSIS installer asset attached to a release (productName-version-setup.exe). */
function setupAsset(release: GithubRelease): { name: string; url: string; size?: number } | null {
  const asset = release.assets?.find((a) => /setup.*\.exe$/i.test(a.name))
  return asset ? { name: asset.name, url: asset.browser_download_url, size: asset.size } : null
}

function versionOf(release: GithubRelease): string | undefined {
  return release.tag_name?.replace(/^v/i, '')
}

/* ---------------------------------------------------------------------------
 * electron-updater wiring (installed builds)
 * ------------------------------------------------------------------------- */

function bindAutoUpdater(): void {
  const autoUpdater = getAutoUpdater()
  autoUpdater.autoDownload = false
  autoUpdater.autoInstallOnAppQuit = true
  // The launcher is a normal per-user app; never silently restart under the user.
  autoUpdater.autoRunAppAfterInstall = true

  autoUpdater.on('checking-for-update', () => patch({ phase: 'checking', error: undefined }))
  autoUpdater.on('update-available', (info: UpdaterFeedInfo) => {
    patch({
      phase: 'available',
      latest: info.version,
      notes: typeof info.releaseNotes === 'string' ? info.releaseNotes : undefined
    })
  })
  autoUpdater.on('update-not-available', (info: UpdaterFeedInfo) =>
    patch({ phase: 'not-available', latest: info?.version })
  )
  autoUpdater.on('download-progress', (p) =>
    patch({
      phase: 'downloading',
      percent: Math.round(p.percent * 10) / 10,
      transferred: p.transferred,
      total: p.total,
      bytesPerSecond: p.bytesPerSecond
    })
  )
  autoUpdater.on('update-downloaded', (info: UpdaterFeedInfo) =>
    patch({ phase: 'downloaded', latest: info.version, percent: 100 })
  )
  autoUpdater.on('error', (err) =>
    patch({ phase: 'error', error: err instanceof Error ? err.message : String(err) })
  )
}

/* ---------------------------------------------------------------------------
 * Manual fallback (portable / unpackaged builds)
 * ------------------------------------------------------------------------- */

async function downloadManually(): Promise<void> {
  const release = await fetchLatestRelease()
  const asset = setupAsset(release)
  if (!asset) throw new Error('В релизе GitHub нет установщика (*-setup.exe)')
  const latest = versionOf(release)
  if (!latest) throw new Error('GitHub не вернул номер версии')

  const dest = join(tmpdir(), asset.name)
  patch({ phase: 'downloading', latest, percent: 0, transferred: 0, total: asset.size })
  await rm(dest, { force: true }).catch(() => {})

  const res = await net.fetch(asset.url, {
    headers: { 'User-Agent': `vavilon/${app.getVersion()}` },
    signal: AbortSignal.timeout(120000)
  })
  if (!res.ok || !res.body) throw new Error(`Скачивание вернуло ${res.status}`)

  const total = Number(res.headers.get('content-length')) || asset.size || 0
  let transferred = 0
  const out = createWriteStream(dest)
  const startedAt = Date.now()
  for await (const chunk of res.body as unknown as AsyncIterable<Uint8Array>) {
    transferred += chunk.length
    out.write(chunk)
    if (total > 0) {
      const elapsed = Math.max(0.001, (Date.now() - startedAt) / 1000)
      patch({
        phase: 'downloading',
        transferred,
        total,
        percent: Math.round((transferred / total) * 1000) / 10,
        bytesPerSecond: Math.round(transferred / elapsed)
      })
    }
  }
  await new Promise<void>((resolve, reject) => {
    out.end((err?: Error | null) => (err ? reject(err) : resolve()))
  })

  manualInstaller = dest
  patch({ phase: 'downloaded', percent: 100, latest })
}

/* ---------------------------------------------------------------------------
 * Public actions
 * ------------------------------------------------------------------------- */

export async function checkForUpdatesNow(): Promise<UpdaterState> {
  if (isPortable()) {
    patch({ phase: 'checking', error: undefined })
    try {
      const release = await fetchLatestRelease()
      const latest = versionOf(release)
      const asset = setupAsset(release)
      if (latest && asset) {
        patch({ phase: 'available', latest, url: release.html_url, notes: release.body })
      } else {
        patch({ phase: 'not-available' })
      }
    } catch (e) {
      patch({ phase: 'error', error: e instanceof Error ? e.message : String(e) })
    }
    return state
  }

  try {
    await getAutoUpdater().checkForUpdates()
  } catch (e) {
    patch({ phase: 'error', error: e instanceof Error ? e.message : String(e) })
  }
  return state
}

export async function downloadUpdateNow(): Promise<UpdaterState> {
  try {
    if (isPortable()) await downloadManually()
    else await getAutoUpdater().downloadUpdate()
  } catch (e) {
    patch({ phase: 'error', error: e instanceof Error ? e.message : String(e) })
  }
  return state
}

export async function installUpdateNow(): Promise<boolean> {
  if (isPortable()) {
    if (!manualInstaller) return false
    await shell.openPath(manualInstaller)
    app.quit()
    return true
  }
  // silent=false → show the NSIS UI; forceRunAfter=true → relaunch the app
  setImmediate(() => getAutoUpdater().quitAndInstall(false, true))
  return true
}

/**
 * Starts the background check loop. Only the automatic check is gated by the
 * `autoUpdateCheck` setting — a manual check from the UI always works.
 */
export function startUpdater(): void {
  if (initialized) return
  initialized = true
  if (!isPortable()) bindAutoUpdater()

  const run = (): void => {
    if (!loadSettings().general.autoUpdateCheck) return
    void checkForUpdatesNow().then(() => {
      // auto-download once an update is found, so the user only has to confirm the install
      if (state.phase === 'available') void downloadUpdateNow()
    })
  }

  // Delay the first check so it never competes with window startup / metadata.
  setTimeout(run, 8000)
  timer = setInterval(run, CHECK_INTERVAL_MS)
}

export function stopUpdater(): void {
  if (timer) {
    clearInterval(timer)
    timer = null
  }
}

export function registerAutoUpdateIpc(): void {
  ipcMain.handle('updater:state', () => getUpdaterState())
  ipcMain.handle('updater:check', () => checkForUpdatesNow())
  ipcMain.handle('updater:download', () => downloadUpdateNow())
  ipcMain.handle('updater:install', () => installUpdateNow())
}
